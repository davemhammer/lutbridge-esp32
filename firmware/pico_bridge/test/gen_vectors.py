"""Generate vectors.h from the Python oracle (lutron_pico.py).

The oracle stays the single source of truth: the nine captured air-bit bursts,
the published bodies, the set-level captures, and the exact event lines its own
Grouper and format_event print for a set of timed scenarios. Nothing here is a
private vector set.

    python3 -I firmware/pico_bridge/test/gen_vectors.py <oracle_dir> > firmware/pico_bridge/test/vectors.h

<oracle_dir> is the directory containing lutron_pico.py.
"""
import sys
from pathlib import Path

if len(sys.argv) < 2:
    sys.exit("usage: gen_vectors.py <dir containing lutron_pico.py>")
oracle_dir = sys.argv[1]
sys.path.insert(0, oracle_dir)
import lutron_pico as lp  # noqa: E402


def body(serial, button, action, seq, toggle):
    return lp.build_body(bytes.fromhex(serial), lp.BUTTONS[button], action, seq, toggle)


SPARE = "02dd0abf"
OTHER = "02a24c77"

SCENARIOS = []


def scenario(name, frames):
    """frames: list of (ms, body bytes)."""
    SCENARIOS.append((name, frames))


scenario("press then release", (
    [(75 * i, body(SPARE, "on", "press", 6 * i, 0)) for i in range(4)]
    + [(700 + 75 * i, body(SPARE, "on", "release", 6 * i, 0)) for i in range(3)]
))
scenario("extra +1 copies are one press", [
    (0, body(SPARE, "on", "press", 0, 1)),
    (12, body(SPARE, "on", "press", 1, 1)),
    (75, body(SPARE, "on", "press", 6, 1)),
    (87, body(SPARE, "on", "press", 7, 1)),
])
scenario("toggle flip splits two presses inside 200 ms", [
    (0, body(SPARE, "on", "press", 0, 0)),
    (100, body(SPARE, "on", "press", 0, 1)),
])
scenario("hold labels a press of 2 s or more", [
    (75 * i, body(SPARE, "raise", "press", (6 * i) & 0xFF, 0)) for i in range(31)
])
scenario("different button splits", [
    (0, body(SPARE, "on", "press", 0, 0)),
    (100, body(SPARE, "off", "press", 0, 0)),
])
scenario("different serial splits", [
    (0, body(SPARE, "on", "press", 0, 0)),
    (50, body(OTHER, "on", "press", 0, 0)),
])
scenario("gap over 200 ms splits", [
    (0, body(SPARE, "on", "press", 0, 0)),
    (300, body(SPARE, "on", "press", 6, 0)),
])
A1 = bytes.fromhex(lp.SET_LEVEL_CAP["last"][0])
A3 = bytes.fromhex("8382a3916f00210e00033ca7a6fe400273e90001000059c5")
OTHER_LEVEL = bytearray(A1)
OTHER_LEVEL[16:18] = b"\xce\x0f"
scenario("set-level pair groups, next level splits", [
    (10000, A1), (10013, A3), (10050, bytes(OTHER_LEVEL)),
])


def run_oracle(frames):
    g = lp.Grouper()
    events = []
    for ms, b in frames:
        done = g.add(lp.Frame(ms / 1000.0, b, True))
        if done:
            events.append(done)
    done = g.flush()
    if done:
        events.append(done)
    return [lp.format_event(ev, True, 0.0) for ev in events]


out = []
w = out.append
w("/* Generated by gen_vectors.py from lutron_pico.py. Do not edit. */")
w("#pragma once")
w("#include <stddef.h>")
w("")
w("typedef struct { const char *hex; const char *bits; } vec_fixture_t;")
w("static const vec_fixture_t k_fixtures[] = {")
for hexbody, bits in lp.FIXTURES.items():
    w(f'    {{"{hexbody}", "{bits}"}},')
w("};")
w("")
w("typedef struct { const char *name; const char *hex; } vec_published_t;")
w("static const vec_published_t k_published[] = {")
for name, (_s, _b, _a, _q, _t, hexbody) in lp.PUBLISHED.items():
    w(f'    {{"{name}", "{hexbody}"}},')
w("};")
w("")
w("typedef struct { const char *name; const char *hex; const char *percent; unsigned word; } vec_setlevel_t;")
w("static const vec_setlevel_t k_setlevel[] = {")
for name, (hexbody, pct, word) in lp.SET_LEVEL_CAP.items():
    w(f'    {{"{name}", "{hexbody}", "{pct}", 0x{word:04X}}},')
w("};")
w("")
w("typedef struct { int ms; const char *hex; } vec_frame_t;")
w("typedef struct {")
w("    const char *name;")
w("    const vec_frame_t *frames; size_t nframes;")
w("    const char *const *lines; size_t nlines;")
w("} vec_scenario_t;")
w("")
for i, (name, frames) in enumerate(SCENARIOS):
    w(f"static const vec_frame_t k_s{i}_frames[] = {{")
    for ms, b in frames:
        w(f'    {{{ms}, "{b.hex()}"}},')
    w("};")
    lines = run_oracle(frames)
    w(f"static const char *const k_s{i}_lines[] = {{")
    for ln in lines:
        assert '"' not in ln and "\\" not in ln
        w(f'    "{ln}",')
    w("};")
w("static const vec_scenario_t k_scenarios[] = {")
for i, (name, frames) in enumerate(SCENARIOS):
    nl = len(run_oracle(frames))
    w(f'    {{"{name}", k_s{i}_frames, {len(frames)}, k_s{i}_lines, {nl}}},')
w("};")
print("\n".join(out))
